export type MessageKey = keyof typeof en;

/**
 * Plural categories beyond `other`. A language may need forms English does
 * not — Russian has `one`/`few`/`many` where English has one plural — so these
 * are optional rather than part of `MessageKey`. The bare key is always the
 * `other` form, which is why it stays required.
 */
type PluralCategory = 'zero' | 'one' | 'two' | 'few' | 'many';

export type Messages = Record<MessageKey, string> &
  Partial<Record<`${MessageKey}_${PluralCategory}`, string>>;

